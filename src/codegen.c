void generate_var(ASTNode* node) {
    if (!node) return;
    
    const char* name = node->name;
    const char* type_name = c_type_name(node->data_type);
    
    fprintf(output, "// Variable: %s\n", name);
    
    if (node->type == NODE_ARRAY_VAR) {
        fprintf(output, "static %s %s[%d]", type_name, name, node->array_size);
        if (node->right) {
            fprintf(output, " = { ");
            // Generate initializer
            fprintf(output, "0");
            for (int i = 1; i < node->array_size; i++) {
                fprintf(output, ", 0");
            }
            fprintf(output, " }");
        }
        fprintf(output, ";\n\n");
    } else {
        fprintf(output, "static %s %s", type_name, name);
        if (node->right) {
            fprintf(output, " = ");
            generate_expr(node->right);
        }
        fprintf(output, ";\n\n");
    }
}

