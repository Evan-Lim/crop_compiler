void generate_main_loop() {
    fprintf(output, "__attribute__((weak)) void setup() { init_crop(); }\n\n");
    fprintf(output, "__attribute__((weak)) void loop() {\n");
    indent_level++;
    // Call every blocks (if any)
    if (every_counter > 0) {
        fprintf(output, "  // Periodic tasks\n");
        for (int i = 0; i < every_counter; i++) {
            fprintf(output, "  every_%d();\n", i);
        }
        fprintf(output, "\n");
    }
    // Call rules
    if (rule_count > 0) {
        fprintf(output, "  // Rules\n");
        for (int i = 0; i < rule_count; i++) {
            // rule_names[i] is the name string from the AST, but function name is sanitized
            char safe[256];
            strncpy(safe, rule_names[i], sizeof(safe)-1);
            for (int j = 0; safe[j]; j++) {
                if (!((safe[j] >= 'a' && safe[j] <= 'z') ||
                      (safe[j] >= 'A' && safe[j] <= 'Z') ||
                      (safe[j] >= '0' && safe[j] <= '9') ||
                      safe[j] == '_')) safe[j] = '_';
            }
            safe[255] = '\0';
            fprintf(output, "  rule_%s();\n", safe);
        }
        fprintf(output, "\n");
    }
    // Call state machines (simplified – we'll just call any machine_process functions)
    // Not implemented yet.
    indent_level--;
    fprintf(output, "}\n\n");

    // main() as before (weak)
    fprintf(output, "#ifndef ARDUINO\n");
    fprintf(output, "__attribute__((weak)) int main() { setup(); while(1) { loop(); millis_counter++; } return 0; }\n");
    fprintf(output, "#endif\n");
}

