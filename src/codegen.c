static FILE* output = NULL;
static int indent_level = 0;
static CompilerOptions* compiler_opts = NULL;
static int unique_counter = 0;

// ============================================================
// Helper functions
// ============================================================

int get_indent_level() {
    return indent_level;
}

void indent(int level) {
    for (int i = 0; i < level * 2; i++) {
        fprintf(output, " ");
    }
}

const char* c_type_name(DataType type) {
    switch (type) {
        case TYPE_U8: return "uint8_t";
        case TYPE_U16: return "uint16_t";
        case TYPE_U32: return "uint32_t";
        case TYPE_U64: return "uint64_t";
        case TYPE_I8: return "int8_t";
        case TYPE_I16: return "int16_t";
        case TYPE_I32: return "int32_t";
        case TYPE_I64: return "int64_t";
        case TYPE_F32: return "float";
        case TYPE_F64: return "double";
        case TYPE_BOOL: return "bool";
        case TYPE_VOID: return "void";
        default: return "void";
    }
}

const char* sanitize_name(const char* name) {
    // Replace spaces and special characters
    static char buffer[256];
    strncpy(buffer, name, sizeof(buffer) - 1);
    buffer[sizeof(buffer) - 1] = '\0';
    for (int i = 0; buffer[i]; i++) {
        if (!((buffer[i] >= 'a' && buffer[i] <= 'z') ||
              (buffer[i] >= 'A' && buffer[i] <= 'Z') ||
              (buffer[i] >= '0' && buffer[i] <= '9') ||
              buffer[i] == '_')) {
            buffer[i] = '_';
        }
    }
    return buffer;
}

