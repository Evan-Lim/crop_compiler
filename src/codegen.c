void generate_rule(ASTNode* node) {
    if (!node) return;
    
    const char* name = node->value.string ? node->value.string : "anonymous";
    const char* safe_name = sanitize_name(name);
    
    fprintf(output, "// Rule: %s\n", name);
    fprintf(output, "void rule_%s() {\n", safe_name);
    indent_level++;
    
    // Generate body
    if (node->children) {
        ASTList* list = node->children;
        while (list) {
            generate_statement(list->node);
            list = list->next;
        }
    }
    
    indent_level--;
    fprintf(output, "}\n\n");
}

void generate_statement(ASTNode* node) {
    if (!node) return;
    
    switch (node->type) {
        case NODE_IF:
            generate_if(node);
            break;
        case NODE_RETURN:
            indent(indent_level);
            fprintf(output, "return");
            if (node->left) {
                fprintf(output, " ");
                generate_expr(node->left);
            }
            fprintf(output, ";\n");
            break;
        case NODE_LET:
            // let inside a block
            indent(indent_level);
            fprintf(output, "// let %s = ", node->name);
            if (node->right) generate_expr(node->right);
            fprintf(output, ";\n");
            break;
        case NODE_UNSAFE:
            generate_unsafe(node);
            break;
        case NODE_IDENTIFIER: {
            // Statement that's just an expression (e.g., function call)
            Symbol* sym = lookup_symbol(node->name);
            if (sym && (sym->sym_type == SYM_FN || sym->sym_type == SYM_EXTERN)) {
                indent(indent_level);
                generate_expr(node);
                fprintf(output, ";\n");
            }
            break;
        }
        default:
            // Try as expression
            if (node->type == NODE_BINOP || node->type == NODE_UNOP ||
                node->type == NODE_FUNCTION_CALL) {
                indent(indent_level);
                generate_expr(node);
                fprintf(output, ";\n");
            }
            break;
    }
}

void generate_if(ASTNode* node) {
    if (!node) return;
    
    indent(indent_level);
    fprintf(output, "if (");
    if (node->left) generate_expr(node->left);
    fprintf(output, ") {\n");
    indent_level++;
    
    // Body
    if (node->children) {
        ASTList* list = node->children;
        while (list) {
            generate_statement(list->node);
            list = list->next;
        }
    }
    
    indent_level--;
    indent(indent_level);
    fprintf(output, "}");
    
    // Else block
    if (node->right) {
        if (node->right->type == NODE_ELSE_IF) {
            fprintf(output, " else ");
            generate_if(node->right);
        } else if (node->right->type == NODE_ELSE) {
            fprintf(output, " else {\n");
            indent_level++;
            if (node->right->children) {
                ASTList* list = node->right->children;
                while (list) {
                    generate_statement(list->node);
                    list = list->next;
                }
            }
            indent_level--;
            indent(indent_level);
            fprintf(output, "}");
        }
    }
    fprintf(output, "\n");
}

void generate_every(ASTNode* node) {
    if (!node) return;
    
    static int every_counter = 0;
    int id = every_counter++;
    const char* name = node->value.string ? node->value.string : "anonymous";
    
    // Get interval in milliseconds
    int interval_ms = 1000;
    if (node->left && node->left->type == NODE_INTEGER) {
        interval_ms = node->left->value.integer;
    }
    
    fprintf(output, "// Every block: %s\n", name);
    fprintf(output, "static unsigned long every_%d_last = 0;\n", id);
    fprintf(output, "void every_%d() {\n", id);
    indent_level++;
    
    fprintf(output, "if (millis() - every_%d_last >= %d) {\n", id, interval_ms);
    indent_level++;
    fprintf(output, "every_%d_last = millis();\n", id);
    
    // Body
    if (node->children) {
        ASTList* list = node->children;
        while (list) {
            generate_statement(list->node);
            list = list->next;
        }
    }
    
    indent_level--;
    fprintf(output, "}\n");
    indent_level--;
    fprintf(output, "}\n\n");
}

// ============================================================
// Function code generation
// ============================================================

void generate_fn(ASTNode* node) {
    if (!node) return;
    
    const char* name = node->name;
    const char* return_type = c_type_name(node->data_type);
    
    fprintf(output, "// Function: %s\n", name);
    fprintf(output, "%s %s(", return_type, name);
    
    // Parameters
    if (node->right && node->right->children) {
        ASTList* params = node->right->children;
        bool first = true;
        while (params) {
            if (params->node->type == NODE_PARAM) {
                if (!first) fprintf(output, ", ");
                fprintf(output, "%s %s", 
                        c_type_name(params->node->data_type),
                        params->node->name);
                first = false;
            }
            params = params->next;
        }
    }
    fprintf(output, ") {\n");
    indent_level++;
    
    // Body
    if (node->children) {
        ASTList* list = node->children;
        while (list) {
            generate_statement(list->node);
            list = list->next;
        }
    }
    
    // Default return if no return statement
    if (node->data_type != TYPE_VOID) {
        indent(indent_level);
        fprintf(output, "return 0;\n");
    }
    
    indent_level--;
    fprintf(output, "}\n\n");
}

