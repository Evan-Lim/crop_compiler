void generate_sensor(ASTNode* node) {
    if (!node) return;
    
    const char* name = node->name;
    const char* pin = node->left ? node->left->name : "0";
    int poll_ms = 100;
    bool has_range = false;
    float range_min = 0.0, range_max = 100.0;
    
    // Get poll interval from children
    if (node->children) {
        ASTList* list = node->children;
        while (list) {
            if (list->node->type == NODE_POLL && list->node->left) {
                poll_ms = list->node->left->value.integer;
            }
            list = list->next;
        }
    }
    
    // Get range if present
    if (node->right && node->right->type == NODE_RANGE) {
        has_range = true;
        if (node->right->left && node->right->left->type == NODE_INTEGER) {
            range_min = node->right->left->value.integer;
        } else if (node->right->left && node->right->left->type == NODE_FLOAT) {
            range_min = node->right->left->value.float_val;
        }
        if (node->right->right && node->right->right->type == NODE_INTEGER) {
            range_max = node->right->right->value.integer;
        } else if (node->right->right && node->right->right->type == NODE_FLOAT) {
            range_max = node->right->right->value.float_val;
        }
    }
    
    bool is_analog = (pin[0] == 'A' || pin[0] == 'a');
    
    fprintf(output, "// Sensor: %s on pin %s\n", name, pin);
    fprintf(output, "#define SENSOR_%s_PIN %s\n", sanitize_name(name).toUpperCase(), pin);
    fprintf(output, "#define SENSOR_%s_POLL %d\n", sanitize_name(name).toUpperCase(), poll_ms);
    
    // Generate read function
    fprintf(output, "static bool sensor_%s_valid = false;\n", sanitize_name(name));
    fprintf(output, "static %s sensor_%s_value = 0;\n", 
            is_analog ? (has_range ? "float" : "uint16_t") : "bool",
            sanitize_name(name));
    fprintf(output, "static unsigned long sensor_%s_last_read = 0;\n", sanitize_name(name));
    fprintf(output, "\n");
    
    // Read function
    fprintf(output, "void sensor_%s_update() {\n", sanitize_name(name));
    fprintf(output, "  if (millis() - sensor_%s_last_read >= %d) {\n", sanitize_name(name), poll_ms);
    fprintf(output, "    sensor_%s_last_read = millis();\n", sanitize_name(name));
    
    if (is_analog) {
        if (has_range) {
            fprintf(output, "    int raw = analogRead(%s);\n", pin);
            fprintf(output, "    sensor_%s_value = (float)raw / 1023.0 * (%.2f - %.2f) + %.2f;\n",
                    sanitize_name(name), range_max, range_min, range_min);
            fprintf(output, "    sensor_%s_valid = true;\n", sanitize_name(name));
        } else {
            fprintf(output, "    sensor_%s_value = analogRead(%s);\n", sanitize_name(name), pin);
            fprintf(output, "    sensor_%s_valid = true;\n", sanitize_name(name));
        }
    } else {
        fprintf(output, "    sensor_%s_value = digitalRead(%s);\n", sanitize_name(name), pin);
        fprintf(output, "    sensor_%s_valid = true;\n", sanitize_name(name));
    }
    fprintf(output, "  }\n");
    fprintf(output, "}\n\n");
    
    // Read function with Option<T> semantics
    fprintf(output, "static bool sensor_%s_read(%s* value) {\n", sanitize_name(name),
            is_analog ? (has_range ? "float" : "uint16_t") : "bool");
    fprintf(output, "  sensor_%s_update();\n", sanitize_name(name));
    fprintf(output, "  if (!sensor_%s_valid) return false;\n", sanitize_name(name));
    fprintf(output, "  *value = sensor_%s_value;\n", sanitize_name(name));
    fprintf(output, "  sensor_%s_valid = false;\n", sanitize_name(name));
    fprintf(output, "  return true;\n");
    fprintf(output, "}\n\n");
    
    // Convenience function for ? operator
    fprintf(output, "static %s sensor_%s_read_opt() {\n", 
            is_analog ? (has_range ? "float" : "uint16_t") : "bool");
    fprintf(output, "  %s val = 0;\n", is_analog ? (has_range ? "float" : "uint16_t") : "bool");
    fprintf(output, "  if (sensor_%s_read(&val)) return val;\n", sanitize_name(name));
    fprintf(output, "  // Return NaN to indicate error (will be caught by ?)\n");
    if (is_analog && has_range) {
        fprintf(output, "  return NAN;\n");
    } else if (is_analog) {
        fprintf(output, "  return 0xFFFF;\n");
    } else {
        fprintf(output, "  return false;\n");
    }
    fprintf(output, "}\n\n");
}

void generate_output(ASTNode* node) {
    if (!node) return;
    
    const char* name = node->name;
    const char* pin = node->left ? node->left->name : "0";
    const char* initial = "OFF";
    
    if (node->right && node->right->type == NODE_STATE_LITERAL) {
        initial = node->right->value.string;
    }
    
    fprintf(output, "// Output: %s on pin %s\n", name, pin);
    fprintf(output, "#define OUTPUT_%s_PIN %s\n", sanitize_name(name), pin);
    fprintf(output, "static bool output_%s_state = %s;\n", sanitize_name(name), 
            strcmp(initial, "ON") == 0 ? "true" : "false");
    fprintf(output, "\n");
    
    fprintf(output, "void output_%s_set(bool state) {\n", sanitize_name(name));
    fprintf(output, "  output_%s_state = state;\n", sanitize_name(name));
    fprintf(output, "  digitalWrite(%s, state ? HIGH : LOW);\n", pin);
    fprintf(output, "}\n\n");
    
    fprintf(output, "bool output_%s_get() {\n", sanitize_name(name));
    fprintf(output, "  return digitalRead(%s);\n", pin);
    fprintf(output, "}\n\n");
}

