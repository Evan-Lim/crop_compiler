// State machine code generation
// ============================================================

void generate_machine(ASTNode* node) {
    if (!node) return;
    
    const char* name = node->name;
    
    fprintf(output, "// ============================================================\n");
    fprintf(output, "// State Machine: %s\n", name);
    fprintf(output, "// ============================================================\n\n");
    
    // State enum
    fprintf(output, "typedef enum {\n");
    indent_level++;
    
    // Collect states
    if (node->children) {
        ASTList* list = node->children;
        while (list) {
            if (list->node->type == NODE_STATE_DECL || 
                list->node->type == NODE_INITIAL_STATE) {
                indent(indent_level);
                const char* state_name = list->node->name;
                fprintf(output, "STATE_%s_%s", sanitize_name(name), sanitize_name(state_name));
                if (list->node->type == NODE_INITIAL_STATE) {
                    fprintf(output, " = 0");
                }
                fprintf(output, ",\n");
            }
            list = list->next;
        }
    }
    
    indent_level--;
    fprintf(output, "} MachineState_%s;\n\n", sanitize_name(name));
    
    // State variable
    fprintf(output, "static MachineState_%s machine_%s_state = STATE_%s_initial;\n\n",
            sanitize_name(name), sanitize_name(name), sanitize_name(name));
    
    // State transition function
    fprintf(output, "void machine_%s_transition(MachineState_%s new_state) {\n",
            sanitize_name(name), sanitize_name(name));
    indent_level++;
    fprintf(output, "machine_%s_state = new_state;\n", sanitize_name(name));
    indent_level--;
    fprintf(output, "}\n\n");
    
    // Process function
    fprintf(output, "void machine_%s_process() {\n", sanitize_name(name));
    indent_level++;
    fprintf(output, "switch (machine_%s_state) {\n", sanitize_name(name));
    indent_level++;
    
    // Generate state handlers
    if (node->children) {
        ASTList* list = node->children;
        while (list) {
            if (list->node->type == NODE_STATE_DECL || 
                list->node->type == NODE_INITIAL_STATE) {
                const char* state_name = list->node->name;
                fprintf(output, "case STATE_%s_%s:\n", 
                        sanitize_name(name), sanitize_name(state_name));
                indent_level++;
                
                // Generate on_enter if present
                if (list->node->children) {
                    ASTList* inner = list->node->children;
                    while (inner) {
                        if (inner->node->type == NODE_ON_ENTER) {
                            fprintf(output, "// on_enter\n");
                            if (inner->node->children) {
                                ASTList* body = inner->node->children;
                                while (body) {
                                    generate_statement(body->node);
                                    body = body->next;
                                }
                            }
                        }
                        inner = inner->next;
                    }
                }
                
                // Generate transitions
                // (Simplified - would need to evaluate conditions)
                
                indent_level--;
                fprintf(output, "break;\n");
            }
            list = list->next;
        }
    }
    
    indent_level--;
    fprintf(output, "}\n");
    indent_level--;
    fprintf(output, "}\n\n");
}

// ============================================================
// Expression generation
// ============================================================

void generate_expr(ASTNode* node) {
    if (!node) return;
    
    switch (node->type) {
        case NODE_INTEGER:
            fprintf(output, "%d", node->value.integer);
            break;
            
        case NODE_FLOAT:
            fprintf(output, "%f", node->value.float_val);
            break;
            
        case NODE_IDENTIFIER:
            fprintf(output, "%s", node->name);
            break;
            
        case NODE_BINOP:
            fprintf(output, "(");
            generate_expr(node->left);
            fprintf(output, " %s ", node->value.string);
            generate_expr(node->right);
            fprintf(output, ")");
            break;
            
        case NODE_UNOP:
            if (strcmp(node->value.string, "not") == 0) {
                fprintf(output, "!");
                generate_expr(node->left);
            } else {
                fprintf(output, "%s", node->value.string);
                generate_expr(node->left);
            }
            break;
            
        case NODE_FUNCTION_CALL:
            fprintf(output, "%s(", node->name);
            if (node->children) {
                ASTList* args = node->children;
                bool first = true;
                while (args) {
                    if (!first) fprintf(output, ", ");
                    generate_expr(args->node);
                    first = false;
                    args = args->next;
                }
            }
            fprintf(output, ")");
            break;
            
        case NODE_QUESTION:
            // ? operator - read sensor with Option<T> semantics
            fprintf(output, "sensor_%s_read_opt()", sanitize_name(node->name));
            break;
            
        case NODE_IS:
            // is operator
            generate_expr(node->left);
            fprintf(output, " == ");
            fprintf(output, "%s", strcmp(node->value.string, "ON") == 0 ? "true" : "false");
            break;
            
        case NODE_STATE_LITERAL:
            fprintf(output, "%s", strcmp(node->value.string, "ON") == 0 ? "true" : "false");
            break;
            
        default:
            fprintf(output, "/* unknown expression */");
            break;
    }
}

