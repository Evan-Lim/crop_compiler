void generate_init(ASTNode* node) {
    if (!node) return;
    fprintf(output, "static void init_crop() {\n");
    indent_level++;
    if (node->children) {
        ASTList* list = node->children;
        while (list) {
            if (list->node->type == NODE_UNSAFE) generate_unsafe(list->node);
            else { indent(indent_level); fprintf(output, "/* unknown init */\n"); }
            list = list->next;
        }
    }
    indent_level--;
    fprintf(output, "}\n\n");
}

void generate_unsafe(ASTNode* node) {
    if (!node) return;
    indent(indent_level);
    if (node->value.string) fprintf(output, "%s\n", node->value.string);
    else fprintf(output, "/* unsafe block */\n");
}

void generate_extern(ASTNode* node) {
    if (!node) return;
    fprintf(output, "extern %s %s(", c_type_name(node->data_type), node->name);
    if (node->children) {
        ASTList* params = node->children; bool first = true;
        while (params) {
            if (params->node->type == NODE_PARAM) {
                if (!first) fprintf(output, ", ");
                fprintf(output, "%s %s", c_type_name(params->node->data_type), params->node->name);
                first = false;
            }
            params = params->next;
        }
    }
    fprintf(output, ");\n\n");
}

