void generate_sensor(ASTNode* node) {
    if (!node) return;
    const char* name = node->name;
    const char* pin = node->value.string ? node->value.string : "0";
    const char* safe = sanitize_name(name);
    const char* upper = to_upper_case(safe);
    int poll_ms = 100;
    bool has_range = false;
    float range_min = 0.0, range_max = 100.0;

    if (node->children) {
        ASTList* list = node->children;
        while (list) {
            if (list->node->type == NODE_POLL && list->node->left) {
                poll_ms = list->node->left->value.integer;
            }
            list = list->next;
        }
    }

    if (node->right && node->right->type == NODE_RANGE) {
        has_range = true;
        if (node->right->left && node->right->left->type == NODE_INTEGER) range_min = node->right->left->value.integer;
        else if (node->right->left && node->right->left->type == NODE_FLOAT) range_min = node->right->left->value.float_val;
        if (node->right->right && node->right->right->type == NODE_INTEGER) range_max = node->right->right->value.integer;
        else if (node->right->right && node->right->right->type == NODE_FLOAT) range_max = node->right->right->value.float_val;
    }

    bool is_analog = (pin[0] == 'A' || pin[0] == 'a');
    fprintf(output, "// Sensor %s on pin %s\n", name, pin);
    fprintf(output, "#define SENSOR_%s_PIN %s\n", upper, pin);
    fprintf(output, "#define SENSOR_%s_POLL %d\n", upper, poll_ms);
    fprintf(output, "static bool sensor_%s_valid = false;\n", safe);
    fprintf(output, "static %s sensor_%s_value = 0;\n",
            is_analog ? (has_range ? "float" : "uint16_t") : "bool", safe);
    fprintf(output, "static unsigned long sensor_%s_last_read = 0;\n", safe);
    fprintf(output, "void sensor_%s_update() {\n", safe);
    fprintf(output, "  if (millis() - sensor_%s_last_read >= %d) {\n", safe, poll_ms);
    fprintf(output, "    sensor_%s_last_read = millis();\n", safe);
    if (is_analog) {
        if (has_range) {
            fprintf(output, "    int raw = analogRead(%s);\n", pin);
            fprintf(output, "    sensor_%s_value = (float)raw / 1023.0 * (%.2f - %.2f) + %.2f;\n",
                    safe, range_max, range_min, range_min);
        } else {
            fprintf(output, "    sensor_%s_value = analogRead(%s);\n", safe, pin);
        }
        fprintf(output, "    sensor_%s_valid = true;\n", safe);
    } else {
        fprintf(output, "    sensor_%s_value = digitalRead(%s);\n", safe, pin);
        fprintf(output, "    sensor_%s_valid = true;\n", safe);
    }
    fprintf(output, "  }\n}\n\n");
    fprintf(output, "static bool sensor_%s_read(%s* value) {\n", safe,
            is_analog ? (has_range ? "float" : "uint16_t") : "bool");
    fprintf(output, "  sensor_%s_update();\n", safe);
    fprintf(output, "  if (!sensor_%s_valid) return false;\n", safe);
    fprintf(output, "  *value = sensor_%s_value;\n", safe);
    fprintf(output, "  sensor_%s_valid = false;\n", safe);
    fprintf(output, "  return true;\n}\n\n");
    fprintf(output, "static %s sensor_%s_read_opt() {\n",
            is_analog ? (has_range ? "float" : "uint16_t") : "bool", safe);
    fprintf(output, "  %s val = 0;\n", is_analog ? (has_range ? "float" : "uint16_t") : "bool");
    fprintf(output, "  if (sensor_%s_read(&val)) return val;\n", safe);
    if (is_analog && has_range) fprintf(output, "  return NAN;\n");
    else if (is_analog) fprintf(output, "  return 0xFFFF;\n");
    else fprintf(output, "  return false;\n");
    fprintf(output, "}\n\n");
}

void generate_output(ASTNode* node) {
    if (!node) return;
    const char* name = node->name;
    const char* pin = node->value.string ? node->value.string : "0";
    const char* safe = sanitize_name(name);
    const char* initial = "OFF";
    if (node->right && node->right->type == NODE_STATE_LITERAL) initial = node->right->value.string;
    fprintf(output, "// Output %s on pin %s\n", name, pin);
    fprintf(output, "#define OUTPUT_%s_PIN %s\n", to_upper_case(safe), pin);
    fprintf(output, "static bool output_%s_state = %s;\n", safe, strcmp(initial, "ON") == 0 ? "true" : "false");
    fprintf(output, "void output_%s_set(bool state) {\n  output_%s_state = state;\n  digitalWrite(%s, state ? HIGH : LOW);\n}\n\n", safe, safe, pin);
    fprintf(output, "bool output_%s_get() {\n  return digitalRead(%s);\n}\n\n", safe, pin);
}

void generate_var(ASTNode* node) {
    if (!node) return;
    const char* name = node->name;
    const char* type = c_type_name(node->data_type);
    fprintf(output, "static %s %s", type, name);
    if (node->right) { fprintf(output, " = "); generate_expr(node->right); }
    fprintf(output, ";\n\n");
}

void generate_let(ASTNode* node) { (void)node; }

void generate_rule(ASTNode* node) {
    if (!node) return;
    const char* name = node->value.string ? node->value.string : "anon";
    const char* safe = sanitize_name(name);
    fprintf(output, "void rule_%s() {\n", safe);
    indent_level++;
    if (node->children) {
        ASTList* list = node->children;
        while (list) { generate_statement(list->node); list = list->next; }
    }
    indent_level--;
    fprintf(output, "}\n\n");
}

void generate_statement(ASTNode* node) {
    if (!node) return;
    switch (node->type) {
        case NODE_ASSIGN: {
            indent(indent_level);
            if (node->left && node->left->type == NODE_IDENTIFIER) {
                Symbol* sym = lookup_symbol(node->left->name);
                if (sym && sym->sym_type == SYM_OUTPUT) {
                    fprintf(output, "output_%s_set(", sanitize_name(node->left->name));
                    generate_expr(node->right);
                    fprintf(output, ");\n");
                } else {
                    fprintf(output, "%s = ", node->left->name);
                    generate_expr(node->right);
                    fprintf(output, ";\n");
                }
            }
            break;
        }
        case NODE_IF: generate_if(node); break;
        case NODE_RETURN:
            indent(indent_level); fprintf(output, "return");
            if (node->left) { fprintf(output, " "); generate_expr(node->left); }
            fprintf(output, ";\n"); break;
        case NODE_LET:
            indent(indent_level); fprintf(output, "// let %s = ", node->name);
            if (node->right) generate_expr(node->right);
            fprintf(output, ";\n"); break;
        case NODE_UNSAFE: generate_unsafe(node); break;
        case NODE_IDENTIFIER: {
            Symbol* sym = lookup_symbol(node->name);
            if (sym && (sym->sym_type == SYM_FN || sym->sym_type == SYM_EXTERN)) {
                indent(indent_level); generate_expr(node); fprintf(output, ";\n");
            }
            break;
        }
        case NODE_BINOP: case NODE_UNOP: case NODE_FUNCTION_CALL:
            indent(indent_level); generate_expr(node); fprintf(output, ";\n"); break;
        default:
            indent(indent_level);
            if (node->left && node->right) { generate_expr(node); fprintf(output, ";\n"); }
            break;
    }
}

void generate_if(ASTNode* node) {
    if (!node) return;
    indent(indent_level);
    fprintf(output, "if (");
    if (node->left) generate_expr(node->left);
    fprintf(output, ") {\n");
    indent_level++;
    if (node->children) {
        ASTList* list = node->children;
        while (list) { generate_statement(list->node); list = list->next; }
    }
    indent_level--;
    indent(indent_level);
    fprintf(output, "}");
    if (node->right) {
        if (node->right->type == NODE_ELSE_IF) {
            fprintf(output, " else ");
            generate_if(node->right);
        } else if (node->right->type == NODE_ELSE) {
            fprintf(output, " else {\n");
            indent_level++;
            if (node->right->children) {
                ASTList* list = node->right->children;
                while (list) { generate_statement(list->node); list = list->next; }
            }
            indent_level--;
            indent(indent_level);
            fprintf(output, "}");
        }
    }
    fprintf(output, "\n");
}

void generate_every(ASTNode* node) {
    if (!node) return;
    int id = every_counter++;
    int interval = (node->left && node->left->type == NODE_INTEGER) ? node->left->value.integer : 1000;
    fprintf(output, "static unsigned long every_%d_last = 0;\n", id);
    fprintf(output, "void every_%d() {\n", id);
    indent_level++;
    fprintf(output, "if (millis() - every_%d_last >= %d) {\n", id, interval);
    indent_level++;
    fprintf(output, "every_%d_last = millis();\n", id);
    if (node->children) {
        ASTList* list = node->children;
        while (list) { generate_statement(list->node); list = list->next; }
    }
    indent_level--;
    fprintf(output, "}\n");
    indent_level--;
    fprintf(output, "}\n\n");
}

void generate_fn(ASTNode* node) {
    if (!node) return;
    const char* name = node->name;
    const char* ret = c_type_name(node->data_type);
    fprintf(output, "%s %s(", ret, name);
    if (node->right && node->right->children) {
        ASTList* params = node->right->children;
        bool first = true;
        while (params) {
            if (params->node->type == NODE_PARAM) {
                if (!first) fprintf(output, ", ");
                fprintf(output, "%s %s", c_type_name(params->node->data_type), params->node->name);
                first = false;
            }
            params = params->next;
        }
    }
    fprintf(output, ") {\n");
    indent_level++;
    if (node->children) {
        ASTList* list = node->children;
        while (list) { generate_statement(list->node); list = list->next; }
    }
    if (node->data_type != TYPE_VOID) { indent(indent_level); fprintf(output, "return 0;\n"); }
    indent_level--;
    fprintf(output, "}\n\n");
}

void generate_machine(ASTNode* node) {
    if (!node) return;
    const char* name = node->name;
    const char* safe = sanitize_name(name);
    fprintf(output, "// Machine %s (stub)\n", name);
    fprintf(output, "static int machine_%s_state = 0;\n", safe);
    fprintf(output, "void machine_%s_process() {}\n\n", safe);
}

void generate_expr(ASTNode* node) {
    if (!node) return;
    switch (node->type) {
        case NODE_INTEGER: fprintf(output, "%d", node->value.integer); break;
        case NODE_FLOAT: fprintf(output, "%f", node->value.float_val); break;
        case NODE_BOOLEAN: fprintf(output, node->value.integer ? "true" : "false"); break;
        case NODE_IDENTIFIER: {
            Symbol* sym = lookup_symbol(node->name);
            if (sym && sym->sym_type == SYM_OUTPUT)
                fprintf(output, "output_%s_get()", sanitize_name(node->name));
            else
                fprintf(output, "%s", node->name);
            break;
        }
        case NODE_BINOP:
            fprintf(output, "("); generate_expr(node->left);
            fprintf(output, " %s ", node->value.string);
            generate_expr(node->right); fprintf(output, ")"); break;
        case NODE_UNOP:
            if (strcmp(node->value.string, "not") == 0) { fprintf(output, "!"); generate_expr(node->left); }
            else { fprintf(output, "%s", node->value.string); generate_expr(node->left); }
            break;
        case NODE_FUNCTION_CALL:
            fprintf(output, "%s(", node->name);
            if (node->children) {
                ASTList* args = node->children; bool first = true;
                while (args) { if (!first) fprintf(output, ", "); generate_expr(args->node); first = false; args = args->next; }
            }
            fprintf(output, ")"); break;
        case NODE_QUESTION:
            fprintf(output, "sensor_%s_read_opt()", sanitize_name(node->name)); break;
        case NODE_IS:
            generate_expr(node->left);
            fprintf(output, " == %s", strcmp(node->value.string, "ON") == 0 ? "true" : "false");
            break;
        case NODE_STATE_LITERAL:
            fprintf(output, "%s", strcmp(node->value.string, "ON") == 0 ? "true" : "false");
            break;
        default: fprintf(output, "/* unknown */"); break;
    }
}

void generate_invariant(ASTNode* node) {
    if (!node) return;
    const char* name = node->value.string ? node->value.string : "anon";
    fprintf(output, "static bool invariant_%s() { return (", sanitize_name(name));
    if (node->left) generate_expr(node->left);
    fprintf(output, "); }\n\n");
}

