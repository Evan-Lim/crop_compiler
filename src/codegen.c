    indent_level = 0;
    every_counter = 0;
    rule_count = 0;

    fprintf(output, "// Generated by CROP Compiler V2.1.2\n");
    fprintf(output, "#include <stdint.h>\n#include <stdbool.h>\n#include <stdlib.h>\n#include <string.h>\n#include <math.h>\n\n");

