void generate_program(ASTNode* node) {
    if (!node || node->type != NODE_PROGRAM) return;
    
    fprintf(output, "// ============================================================\n");
    fprintf(output, "// Global declarations\n");
    fprintf(output, "// ============================================================\n\n");
    
    // Generate all top-level declarations
    ASTList* list = node->children;
    while (list) {
        generate_declaration(list->node);
        list = list->next;
    }
}

void generate_declaration(ASTNode* node) {
    if (!node) return;
    
    switch (node->type) {
        case NODE_SENSOR:
        case NODE_SENSOR_BUS:
            generate_sensor(node);
            break;
        case NODE_OUTPUT:
            generate_output(node);
            break;
        case NODE_VAR:
        case NODE_ARRAY_VAR:
            generate_var(node);
            break;
        case NODE_LET:
            generate_let(node);
            break;
        case NODE_RULE:
            generate_rule(node);
            break;
        case NODE_EVERY:
            generate_every(node);
            break;
        case NODE_FN:
            generate_fn(node);
            break;
        case NODE_MACHINE:
            generate_machine(node);
            break;
        case NODE_INVARIANT:
            generate_invariant(node);
            break;
        case NODE_EMIT:
            generate_emit(node);
            break;
        case NODE_INIT:
            generate_init(node);
            break;
        case NODE_EXTERN:
            generate_extern(node);
            break;
        case NODE_UNSAFE:
            generate_unsafe(node);
            break;
        default:
            break;
    }
}

