void generate_invariant(ASTNode* node) {
    if (!node) return;
    
    const char* name = node->value.string ? node->value.string : "anonymous";
    
    fprintf(output, "// Invariant: %s\n", name);
    fprintf(output, "static bool invariant_%s() {\n", sanitize_name(name));
    indent_level++;
    fprintf(output, "return (");
    if (node->left) generate_expr(node->left);
    fprintf(output, ");\n");
    indent_level--;
    fprintf(output, "}\n\n");
}

void generate_emit(ASTNode* node) {
    if (!node) return;
    
    const char* payload = node->name;
    const char* protocol = node->value.string ? node->value.string : "MQTT";
    const char* address = node->left ? node->left->name : "default";
    
    fprintf(output, "// Emit: %s to %s(%s)\n", payload, protocol, address);
    fprintf(output, "static void emit_%s(", sanitize_name(payload));
    // Generate function signature based on payload fields
    Symbol* sym = lookup_symbol(payload);
    if (sym && sym->fields) {
        Symbol* field = sym->fields;
        bool first = true;
        while (field) {
            if (!first) fprintf(output, ", ");
            fprintf(output, "%s %s", c_type_name(field->data_type), field->name);
            first = false;
            field = field->next;
        }
    }
    fprintf(output, ") {\n");
    indent_level++;
    
    // Generate serialization
    fprintf(output, "// TODO: Implement %s serialization to %s\n", payload, protocol);
    
    indent_level--;
    fprintf(output, "}\n\n");
}

void generate_init(ASTNode* node) {
    if (!node) return;
    
    fprintf(output, "// Initialization\n");
    fprintf(output, "static void init_crop() {\n");
    indent_level++;
    
    // Body
    if (node->children) {
        ASTList* list = node->children;
        while (list) {
            // Assume these are C statements
            if (list->node->type == NODE_UNSAFE) {
                generate_unsafe(list->node);
            } else {
                indent(indent_level);
                fprintf(output, "// %s (C code not supported in init block)\n", 
                        node_type_name(list->node->type));
            }
            list = list->next;
        }
    }
    
    indent_level--;
    fprintf(output, "}\n\n");
}

void generate_unsafe(ASTNode* node) {
    if (!node) return;
    
    indent(indent_level);
    if (node->value.string) {
        fprintf(output, "// Unsafe C code:\n");
        indent(indent_level);
        fprintf(output, "%s\n", node->value.string);
    } else {
        fprintf(output, "/* unsafe block */\n");
    }
}

void generate_extern(ASTNode* node) {
    if (!node) return;
    
    const char* name = node->name;
    const char* return_type = c_type_name(node->data_type);
    const char* lang = node->value.string ? node->value.string : "C";
    
    fprintf(output, "// External function: %s (%s)\n", name, lang);
    fprintf(output, "extern %s %s(", return_type, name);
    
    if (node->children) {
        ASTList* params = node->children;
        bool first = true;
        while (params) {
            if (params->node->type == NODE_PARAM) {
                if (!first) fprintf(output, ", ");
                fprintf(output, "%s %s", 
                        c_type_name(params->node->data_type),
                        params->node->name);
                first = false;
            }
            params = params->next;
        }
    }
    fprintf(output, ");\n\n");
}

