bool generate_c_code(ASTNode* node, const char* output_file, CompilerOptions* opts) {
    output = fopen(output_file, "w");
    if (!output) {
        fprintf(stderr, "ERROR: Cannot open output file: %s\n", output_file);
        return false;
    }
    
    compiler_opts = opts;
    indent_level = 0;
    
    // Generate header
    fprintf(output, "// ============================================================\n");
    fprintf(output, "// Generated by CROP Compiler V2.1.2\n");
    fprintf(output, "// Source: %s\n", compiler_opts ? compiler_opts->input_file : "unknown");
    fprintf(output, "// Target: %s\n", compiler_opts ? compiler_opts->target : "native");
    fprintf(output, "// Date: %s", ctime(&(time_t){time(NULL)}));
    fprintf(output, "// ============================================================\n\n");
    
    // Include headers
    fprintf(output, "#include <stdint.h>\n");
    fprintf(output, "#include <stdbool.h>\n");
    fprintf(output, "#include <stdlib.h>\n");
    fprintf(output, "#include <string.h>\n");
    fprintf(output, "#include <math.h>\n\n");
    
    // Arduino/embedded compatibility
    fprintf(output, "// ============================================================\n");
    fprintf(output, "// Platform compatibility layer\n");
    fprintf(output, "// ============================================================\n\n");
    fprintf(output, "#ifdef ARDUINO\n");
    fprintf(output, "#include <Arduino.h>\n");
    fprintf(output, "#else\n");
    fprintf(output, "// Simulated environment\n");
    fprintf(output, "typedef uint16_t pin_t;\n");
    fprintf(output, "static unsigned long millis_counter = 0;\n");
    fprintf(output, "unsigned long millis() { return millis_counter; }\n");
    fprintf(output, "void delay(unsigned long ms) { /* simulated */ }\n");
    fprintf(output, "#define OUTPUT 1\n");
    fprintf(output, "#define INPUT 0\n");
    fprintf(output, "#define INPUT_PULLUP 2\n");
    fprintf(output, "#define LOW 0\n");
    fprintf(output, "#define HIGH 1\n");
    fprintf(output, "#define RISING 1\n");
    fprintf(output, "#define FALLING 0\n");
    fprintf(output, "#define CHANGE 2\n");
    fprintf(output, "void pinMode(pin_t pin, int mode) {}\n");
    fprintf(output, "void digitalWrite(pin_t pin, int val) {}\n");
    fprintf(output, "int digitalRead(pin_t pin) { return 0; }\n");
    fprintf(output, "int analogRead(pin_t pin) { return 512; }\n");
    fprintf(output, "void attachInterrupt(pin_t pin, void (*fn)(), int mode) {}\n");
    fprintf(output, "#endif\n\n");
    
    // Generate code
    generate_program(node);
    
    // Generate main loop
    generate_main_loop();
    
    fclose(output);
    return true;
}

